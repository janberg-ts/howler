        warnings: List[str] = []
        successful_mappings = 0
        
        for i, evidence_item in enumerate(evidence_list):
            try:
                # Validate evidence item structure
                if not isinstance(evidence_item, dict):
                    warning = f"Evidence item {i} is not a dictionary, skipping"
                    warnings.append(warning)
                    self.logger.warning(warning)
                    continue
                
                odata_type = evidence_item.get('@odata.type')
                if not odata_type:
                    warning = f"Evidence item {i} missing @odata.type field"
                    warnings.append(warning)
                    self.logger.warning(warning)
                    continue
                
                # Get appropriate mapper
                mapper = evidence_mapper_registry.get_mapper(odata_type)
                if not mapper:
                    warning = f"No mapper available for evidence type: {odata_type}"
                    warnings.append(warning)
                    self.logger.warning(warning)
                    continue
                
                # Apply mapping with error isolation
                try:
                    hit = mapper.map(evidence_item, hit)
                    successful_mappings += 1
                    evidence_stats[odata_type] = evidence_stats.get(odata_type, 0) + 1
                    
                    self.logger.debug(
                        "Successfully mapped evidence %d of type %s", 
                        i, odata_type
                    )
                    
                except MappingError as e:
                    warning = f"Failed to map evidence item {i} ({odata_type}): {str(e)}"
                    warnings.append(warning)
                    self.logger.error(warning)
                    continue
                    
                except Exception as e:
                    warning = f"Unexpected error mapping evidence item {i} ({odata_type}): {str(e)}"
                    warnings.append(warning)
                    self.logger.error(warning)
                    continue
                
            except Exception as e:
                warning = f"Critical error processing evidence item {i}: {str(e)}"
                warnings.append(warning)
                self.logger.error(warning)
                continue
        
        # Log evidence processing summary
        self.logger.info(
            "Evidence processing complete: %d/%d successful mappings across %d types",
            successful_mappings, len(evidence_list), len(evidence_stats)
        )
        
        if evidence_stats:
            self.logger.debug("Evidence mapping summary: %s", evidence_stats)
        
        # Finalize process mapping to ensure complete hierarchy
        try:
            self._finalize_process_mapping(hit)
        except Exception as e:
            warning = f"Failed to finalize process mapping: {str(e)}"
            warnings.append(warning)
            self.logger.warning(warning)
        
