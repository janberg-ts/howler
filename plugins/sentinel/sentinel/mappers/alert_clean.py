    def _safe_parse_datetime(self, date_str: Optional[str]) -> Optional[str]:
        """
        Safely parse datetime string with error handling.
        
        Args:
            date_str: ISO datetime string
            
        Returns:
            Validated datetime string or None if invalid
        """
        if not date_str or not isinstance(date_str, str):
            return None
        
        try:
            # Validate the datetime format
            datetime.fromisoformat(date_str.replace('Z', '+00:00'))
            return date_str
        except (ValueError, AttributeError) as e:
            self.logger.debug("Invalid datetime format: %s - %s", date_str, str(e))
            return None
    
